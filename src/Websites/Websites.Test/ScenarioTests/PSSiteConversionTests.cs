using Microsoft.Azure.Commands.WebApps.Models;
using Microsoft.Azure.Commands.WebApps.Utilities;
using Microsoft.Azure.Management.WebSites.Models;
using System.Collections.Generic;
using Xunit;

namespace Microsoft.Azure.Commands.Websites.Test.ScenarioTests
{
    public class PSSiteConversionTests
    {
        [Theory]
        [InlineData(true)]
        [InlineData(false)]
        [InlineData(null)]
        public void WrappingSitePreservesApiProperties(bool? enabled)
        {
            var source = new Site(
                location: "westus",
                id: "/subscriptions/sub/resourceGroups/rg/providers/Microsoft.Web/sites/app",
                name: "app",
                type: "Microsoft.Web/sites",
                systemData: new SystemData(createdBy: "creator"),
                tags: new Dictionary<string, string> { { "environment", "test" } },
                kind: "app",
                siteConfig: new SiteConfig { AlwaysOn = false },
                daprConfig: new DaprConfig(),
                resourceConfig: new ResourceConfig(),
                ipMode: IPMode.IPv4AndIPv6,
                dnsConfiguration: new SiteDnsConfig(),
                outboundVnetRouting: new OutboundVnetRouting(allTraffic: enabled),
                functionAppConfig: new FunctionAppConfig(),
                workloadProfileName: "workload",
                clientAffinityPartitioningEnabled: enabled,
                clientAffinityProxyEnabled: enabled,
                endToEndEncryptionEnabled: enabled,
                sshEnabled: enabled,
                publicNetworkAccess: "Disabled",
                autoGeneratedDomainNameLabelScope: AutoGeneratedDomainNameLabelScope.ResourceGroupReuse,
                managedEnvironmentId: "/subscriptions/sub/resourceGroups/rg/providers/Microsoft.App/managedEnvironments/environment",
                sku: "P1v3");

            var result = new PSSite(new PSSite(source));

            Assert.Equal(source.Id, result.Id);
            Assert.Equal(source.Name, result.Name);
            Assert.Equal(source.Type, result.Type);
            Assert.Equal(source.Location, result.Location);
            Assert.Equal(source.Kind, result.Kind);
            Assert.Same(source.Tags, result.Tags);
            Assert.Same(source.SiteConfig, result.SiteConfig);
            Assert.Same(source.SystemData, result.SystemData);
            Assert.Same(source.DaprConfig, result.DaprConfig);
            Assert.Same(source.ResourceConfig, result.ResourceConfig);
            Assert.Equal(source.IPMode, result.IPMode);
            Assert.Same(source.DnsConfiguration, result.DnsConfiguration);
            Assert.Same(source.OutboundVnetRouting, result.OutboundVnetRouting);
            Assert.Same(source.FunctionAppConfig, result.FunctionAppConfig);
            Assert.Equal(source.WorkloadProfileName, result.WorkloadProfileName);
            Assert.Equal(source.ClientAffinityPartitioningEnabled, result.ClientAffinityPartitioningEnabled);
            Assert.Equal(source.ClientAffinityProxyEnabled, result.ClientAffinityProxyEnabled);
            Assert.Equal(source.EndToEndEncryptionEnabled, result.EndToEndEncryptionEnabled);
            Assert.Equal(source.SshEnabled, result.SshEnabled);
            Assert.Equal(source.PublicNetworkAccess, result.PublicNetworkAccess);
            Assert.Equal(source.AutoGeneratedDomainNameLabelScope, result.AutoGeneratedDomainNameLabelScope);
            Assert.Equal(source.ManagedEnvironmentId, result.ManagedEnvironmentId);
            Assert.Equal(source.Sku, result.Sku);
        }

        [Fact]
        public void UnspecifiedApiPropertiesRemainUnset()
        {
            var result = new PSSite(new Site(location: "westus"));

            Assert.Null(result.SystemData);
            Assert.Null(result.DaprConfig);
            Assert.Null(result.ResourceConfig);
            Assert.Null(result.IPMode);
            Assert.Null(result.DnsConfiguration);
            Assert.Null(result.OutboundVnetRouting);
            Assert.Null(result.FunctionAppConfig);
            Assert.Null(result.WorkloadProfileName);
            Assert.Null(result.ClientAffinityPartitioningEnabled);
            Assert.Null(result.ClientAffinityProxyEnabled);
            Assert.Null(result.EndToEndEncryptionEnabled);
            Assert.Null(result.SshEnabled);
            Assert.Null(result.PublicNetworkAccess);
            Assert.Null(result.AutoGeneratedDomainNameLabelScope);
            Assert.Null(result.ManagedEnvironmentId);
            Assert.Null(result.Sku);
        }

        [Fact]
        public void WrappingPSSitePreservesEnrichedProperties()
        {
            var connection = new VnetInfo { VnetResourceId = "vnet" };
            var source = new PSSite(new Site(location: "westus"))
            {
                AzureStoragePath = new WebAppAzureStoragePath[0],
                VnetInfo = new List<VnetInfo> { connection }
            };

            var result = new PSSite(source);

            Assert.Same(source.AzureStoragePath, result.AzureStoragePath);
            Assert.Same(connection, Assert.Single(result.VnetInfo));
            source.VnetInfo.Clear();
            Assert.Single(result.VnetInfo);
            Assert.Null(new PSSite(source).VnetInfo);
        }
    }
}
