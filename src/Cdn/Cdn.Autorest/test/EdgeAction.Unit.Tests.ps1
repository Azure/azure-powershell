Describe 'EdgeAction.Unit' {
    It 'Preserves common path parameter metadata for <Command>' -TestCases @(
        @{ Command = 'New-AzCdnEdgeActionVersion' }
        @{ Command = 'New-AzCdnEdgeActionExecutionFilter' }
    ) {
        param($Command)
        $metadata = Get-Command $Command -Module Az.Cdn -ErrorAction Stop
        foreach ($name in @('EdgeActionName', 'ResourceGroupName', 'SubscriptionId')) {
            $attributes = @($metadata.Parameters[$name].Attributes |
                Where-Object { $_ -is [System.Management.Automation.ParameterAttribute] })
            $attributes.Count | Should Be 1
            $attributes[0].ParameterSetName | Should Be '__AllParameterSets'
            $attributes[0].Mandatory | Should Be ($name -ne 'SubscriptionId')
        }
        $sets = @($metadata.ParameterSets.Name)
        $sets.Count | Should Be 3
        foreach ($name in @('CreateExpanded', 'CreateViaJsonString', 'CreateViaJsonFilePath')) {
            $sets | Should Contain $name
        }
    }

    It 'Preserves the published deployment output type' {
        $command = Get-Command Deploy-AzCdnEdgeActionVersionCode -Module Az.Cdn -ErrorAction Stop
        $command.OutputType.Name | Should Be 'Microsoft.Azure.PowerShell.Cmdlets.Cdn.Models.IEdgeActionVersionProperties'
    }

    It 'Preserves legacy SDK error callback types' {
        $methods = [Microsoft.Azure.PowerShell.Cmdlets.Cdn.Cdn].GetMethods() |
            Where-Object { $_.Name -match '^EdgeAction' }
        $checked = 0
        foreach ($method in $methods) {
            foreach ($parameter in $method.GetParameters()) {
                if ($parameter.Name -eq 'onDefault') {
                    $checked++
                    $parameter.ParameterType.FullName | Should Match 'Models\.IErrorResponse,'
                    $parameter.ParameterType.FullName | Should Not Match 'IErrorResponseAutoGenerated'
                }
            }
        }
        $checked | Should BeGreaterThan 0
    }

    It 'Preserves writable provisioningState in legacy <Model> requests' -TestCases @(
        @{ Model = 'EdgeAction' }
        @{ Model = 'EdgeActionVersion' }
        @{ Model = 'EdgeActionExecutionFilter' }
    ) {
        param($Model)
        $type = [Microsoft.Azure.PowerShell.Cmdlets.Cdn.Cdn].Assembly.GetType(
            "Microsoft.Azure.PowerShell.Cmdlets.Cdn.Models.$Model", $true)
        $modelObject = [System.Activator]::CreateInstance($type)
        $modelObject.ProvisioningState = 'Succeeded'
        $mode = [Microsoft.Azure.PowerShell.Cmdlets.Cdn.Runtime.SerializationMode]::IncludeCreate -bor
            [Microsoft.Azure.PowerShell.Cmdlets.Cdn.Runtime.SerializationMode]::IncludeUpdate
        $json = $modelObject.ToJson($null, $mode).ToString() | ConvertFrom-Json
        $json.properties.provisioningState | Should Be 'Succeeded'
    }

    It 'Preserves SKU update serialization' {
        $update = [Microsoft.Azure.PowerShell.Cmdlets.Cdn.Models.EdgeActionUpdate]::new()
        $update.SkuName = 'Standard'
        $update.SkuTier = 'Standard'
        $json = $update.ToJsonString() | ConvertFrom-Json
        $json.sku.name | Should Be 'Standard'
        $json.sku.tier | Should Be 'Standard'
        (Get-Command Update-AzCdnEdgeAction).Parameters.ContainsKey('SkuName') | Should Be $true
        (Get-Command Update-AzCdnEdgeAction).Parameters.ContainsKey('SkuTier') | Should Be $true
    }

    It 'Preserves legacy getVersionCode body bindings' {
        $command = Get-Command Get-AzCdnEdgeActionVersionCode -Module Az.Cdn -ErrorAction Stop
        foreach ($name in @('Body', 'JsonString', 'JsonFilePath')) {
            $command.Parameters.ContainsKey($name) | Should Be $true
        }
    }

    It 'Preserves existing CDN completion values on <Model>.<Property>' -TestCases @(
        @{ Model = 'IDeliveryRuleEdgeActionParameters'; Property = 'InvocationPoint'; Values = @(
                'clientRequest', 'originRequest', 'originResponse', 'clientResponse',
                'ClientRequest', 'OriginRequest', 'ClientResponse') }
        @{ Model = 'ICdnWebApplicationFirewallPolicy'; Property = 'ProvisioningState'; Values = @(
                'Succeeded', 'Failed', 'Canceled', 'Provisioning', 'Upgrading') }
        @{ Model = 'ICdnWebApplicationFirewallPolicyProperties'; Property = 'ProvisioningState'; Values = @(
                'Succeeded', 'Failed', 'Canceled', 'Provisioning', 'Upgrading') }
    ) {
        param($Model, $Property, $Values)
        $type = [Microsoft.Azure.PowerShell.Cmdlets.Cdn.Cdn].Assembly.GetType(
            "Microsoft.Azure.PowerShell.Cmdlets.Cdn.Models.$Model", $true)
        $completer = $type.GetProperty($Property).GetCustomAttributes($false) |
            Where-Object { $_ -is [Microsoft.Azure.PowerShell.Cmdlets.Cdn.PSArgumentCompleterAttribute] }
        $actual = @($completer.ScriptBlock.Invoke('', '', '', $null, @{}) | ForEach-Object CompletionText)
        foreach ($value in $Values) {
            ($actual -ccontains $value) | Should Be $true
        }
        $actual.Count | Should Be $Values.Count
    }
}
